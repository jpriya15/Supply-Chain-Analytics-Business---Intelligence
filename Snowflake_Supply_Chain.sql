-- 6.Cleaning the data in STAGING Schema
USE DATABASE SUPPLY_CHAIN_ANALYTICS;
USE SCHEMA STAGING;

CREATE OR REPLACE TABLE STG_SUPPLY_CHAIN_ORDERS AS
SELECT
    -- Identifiers
    TRY_CAST(ORDER_ID AS NUMBER) AS ORDER_ID,
    TRY_CAST(ORDER_ITEM_ID AS NUMBER) AS ORDER_ITEM_ID,
    TRY_CAST(CUSTOMER_ID AS NUMBER) AS CUSTOMER_ID,
    TRY_CAST(PRODUCT_CARD_ID AS NUMBER) AS PRODUCT_ID,
    TRY_CAST(DEPARTMENT_ID AS NUMBER) AS DEPARTMENT_ID,
    TRY_CAST(CATEGORY_ID AS NUMBER) AS CATEGORY_ID,

    -- Dates & Timestamps
    TRY_TO_TIMESTAMP(ORDER_DATE_DATEORDERS, 'MM/DD/YYYY HH24:MI') AS ORDER_TIMESTAMP,
    TRY_TO_DATE(ORDER_DATE_DATEORDERS, 'MM/DD/YYYY HH24:MI') AS ORDER_DATE,
    TRY_TO_TIMESTAMP(SHIPPING_DATE_DATEORDERS, 'MM/DD/YYYY HH24:MI') AS SHIPPING_TIMESTAMP,
    TRY_TO_DATE(SHIPPING_DATE_DATEORDERS, 'MM/DD/YYYY HH24:MI') AS SHIPPING_DATE,

    -- Shipping & Fulfillment
    TRY_CAST(DAYS_FOR_SHIPPING_REAL AS NUMBER) AS ACTUAL_SHIPPING_DAYS,
    TRY_CAST(DAYS_FOR_SHIPMENT_SCHEDULED AS NUMBER) AS SCHEDULED_SHIPPING_DAYS,
    DELIVERY_STATUS,
    TRY_CAST(LATE_DELIVERY_RISK AS NUMBER) = 1 AS IS_LATE_DELIVERY_RISK,
    SHIPPING_MODE,

    -- Financials & Sales Metrics
    TRY_CAST(ORDER_ITEM_QUANTITY AS NUMBER) AS ORDER_QUANTITY,
    TRY_CAST(ORDER_ITEM_PRODUCT_PRICE AS FLOAT) AS PRODUCT_PRICE,
    TRY_CAST(SALES AS FLOAT) AS GROSS_SALES,
    TRY_CAST(ORDER_ITEM_DISCOUNT AS FLOAT) AS DISCOUNT_AMOUNT,
    TRY_CAST(ORDER_ITEM_DISCOUNT_RATE AS FLOAT) AS DISCOUNT_RATE,
    TRY_CAST(ORDER_ITEM_TOTAL AS FLOAT) AS NET_SALES,
    TRY_CAST(ORDER_PROFIT_PER_ORDER AS FLOAT) AS PROFIT_PER_ORDER,
    TRY_CAST(ORDER_ITEM_PROFIT_RATIO AS FLOAT) AS PROFIT_RATIO,

    -- Customer Info
    CUSTOMER_FNAME AS CUSTOMER_FIRST_NAME,
    CUSTOMER_LNAME AS CUSTOMER_LAST_NAME,
    CUSTOMER_SEGMENT,
    CUSTOMER_CITY,
    CUSTOMER_STATE,
    CUSTOMER_COUNTRY,
    CUSTOMER_ZIPCODE,

    -- Geography & Order Details
    MARKET,
    ORDER_REGION,
    ORDER_COUNTRY,
    ORDER_STATE,
    ORDER_CITY,
    ORDER_STATUS,
    TYPE AS PAYMENT_TYPE,

    -- Product Details
    PRODUCT_NAME,
    CATEGORY_NAME,
    DEPARTMENT_NAME
FROM SUPPLY_CHAIN_ANALYTICS.RAW.DATACO_RAW;

