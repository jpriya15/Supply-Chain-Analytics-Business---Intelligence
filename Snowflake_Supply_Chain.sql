-- 8.4.DIM_SHIPPING 
CREATE OR REPLACE TABLE DIM_SHIPPING AS
SELECT DISTINCT
    MD5(CONCAT(
        COALESCE(SHIPPING_MODE, ''),
        COALESCE(DELIVERY_STATUS, ''),
        COALESCE(CAST(IS_LATE_DELIVERY_RISK AS VARCHAR), '')
    )) AS SHIPPING_KEY,
    SHIPPING_MODE,
    DELIVERY_STATUS,
    IS_LATE_DELIVERY_RISK
FROM SUPPLY_CHAIN_ANALYTICS.STAGING.STG_SUPPLY_CHAIN_ORDERS;

-- 8.5.DIM_DATE 
CREATE OR REPLACE TABLE DIM_DATE AS
WITH DATE_RANGE AS (
    SELECT 
        DATEADD(DAY, SEQ4(), '2015-01-01'::DATE) AS DATE_VAL
    FROM TABLE(GENERATOR(ROWCOUNT => 365 * 6)) -- 6 years range (2015 - 2020)
)
SELECT
    DATE_VAL AS DATE_KEY,
    YEAR(DATE_VAL) AS YEAR,
    QUARTER(DATE_VAL) AS QUARTER,
    CONCAT('Q', QUARTER(DATE_VAL), ' ', YEAR(DATE_VAL)) AS QUARTER_YEAR,
    MONTH(DATE_VAL) AS MONTH_NUM,
    MONTHNAME(DATE_VAL) AS MONTH_NAME,
    CONCAT(MONTHNAME(DATE_VAL), ' ', YEAR(DATE_VAL)) AS MONTH_YEAR,
    WEEKOFYEAR(DATE_VAL) AS WEEK_OF_YEAR,
    DAYOFWEEK(DATE_VAL) AS DAY_OF_WEEK_NUM,
    DAYNAME(DATE_VAL) AS DAY_NAME,
    CASE WHEN DAYOFWEEK(DATE_VAL) IN (0, 6) THEN TRUE ELSE FALSE END AS IS_WEEKEND
FROM DATE_RANGE
WHERE DATE_VAL <= '2020-12-31';

-- 8.6.FACT_SALES 
CREATE OR REPLACE TABLE FACT_SALES AS
SELECT
    s.ORDER_ITEM_ID,
    s.ORDER_ID,
    s.CUSTOMER_ID,
    s.PRODUCT_ID,
    
    -- Shipping Key
    MD5(CONCAT(
        COALESCE(s.SHIPPING_MODE, ''),
        COALESCE(s.DELIVERY_STATUS, ''),
        COALESCE(CAST(s.IS_LATE_DELIVERY_RISK AS VARCHAR), '')
    )) AS SHIPPING_KEY,
    
    -- Date Keys (links to DIM_DATE)
    s.ORDER_DATE AS ORDER_DATE_KEY,
    s.SHIPPING_DATE AS SHIPPING_DATE_KEY,
    
    -- Timestamps
    s.ORDER_TIMESTAMP,
    s.SHIPPING_TIMESTAMP,
    
    -- Operational Metrics
    s.ACTUAL_SHIPPING_DAYS,
    s.SCHEDULED_SHIPPING_DAYS,
    (s.ACTUAL_SHIPPING_DAYS - s.SCHEDULED_SHIPPING_DAYS) AS SHIPPING_DELAY_DAYS,
    
    -- Quantitative Financial Measures
    s.ORDER_QUANTITY,
    s.GROSS_SALES,
    s.DISCOUNT_AMOUNT,
    s.DISCOUNT_RATE,
    s.NET_SALES,
    s.PROFIT_PER_ORDER,
    s.PROFIT_RATIO
FROM SUPPLY_CHAIN_ANALYTICS.STAGING.STG_SUPPLY_CHAIN_ORDERS s;

